package termui

import "strings"

// glyphs is a 5x5 block font covering the pairing-code alphabet
// (A-Z without I and O, 2-9) and the dash.
var glyphs = map[rune][5]string{
	'A': {".###.", "#...#", "#####", "#...#", "#...#"},
	'B': {"####.", "#...#", "####.", "#...#", "####."},
	'C': {".####", "#....", "#....", "#....", ".####"},
	'D': {"####.", "#...#", "#...#", "#...#", "####."},
	'E': {"#####", "#....", "####.", "#....", "#####"},
	'F': {"#####", "#....", "####.", "#....", "#...."},
	'G': {".####", "#....", "#..##", "#...#", ".####"},
	'H': {"#...#", "#...#", "#####", "#...#", "#...#"},
	'J': {"..###", "...#.", "...#.", "#..#.", ".##.."},
	'K': {"#...#", "#..#.", "###..", "#..#.", "#...#"},
	'L': {"#....", "#....", "#....", "#....", "#####"},
	'M': {"#...#", "##.##", "#.#.#", "#...#", "#...#"},
	'N': {"#...#", "##..#", "#.#.#", "#..##", "#...#"},
	'P': {"####.", "#...#", "####.", "#....", "#...."},
	'Q': {".###.", "#...#", "#.#.#", "#..#.", ".##.#"},
	'R': {"####.", "#...#", "####.", "#..#.", "#...#"},
	'S': {".####", "#....", ".###.", "....#", "####."},
	'T': {"#####", "..#..", "..#..", "..#..", "..#.."},
	'U': {"#...#", "#...#", "#...#", "#...#", ".###."},
	'V': {"#...#", "#...#", "#...#", ".#.#.", "..#.."},
	'W': {"#...#", "#...#", "#.#.#", "##.##", "#...#"},
	'X': {"#...#", ".#.#.", "..#..", ".#.#.", "#...#"},
	'Y': {"#...#", ".#.#.", "..#..", "..#..", "..#.."},
	'Z': {"#####", "...#.", "..#..", ".#...", "#####"},
	'2': {"####.", "....#", ".###.", "#....", "#####"},
	'3': {"####.", "....#", ".###.", "....#", "####."},
	'4': {"#...#", "#...#", "#####", "....#", "....#"},
	'5': {"#####", "#....", "####.", "....#", "####."},
	'6': {".###.", "#....", "####.", "#...#", ".###."},
	'7': {"#####", "....#", "...#.", "..#..", "..#.."},
	'8': {".###.", "#...#", ".###.", "#...#", ".###."},
	'9': {".###.", "#...#", ".####", "....#", ".###."},
	'-': {".....", ".....", ".###.", ".....", "....."},
}

// BigText renders s in 5-line block letters (unknown characters become
// blanks), each line prefixed with indent. It uses the terminal's own
// foreground colour, so it reads on dark and light themes alike.
func BigText(s, indent string) string {
	var rows [5]strings.Builder
	for i, r := range strings.ToUpper(s) {
		g, ok := glyphs[r]
		if !ok {
			g = [5]string{".....", ".....", ".....", ".....", "....."}
		}
		for y := range rows {
			if i > 0 {
				rows[y].WriteString("  ")
			}
			for _, c := range g[y] {
				if c == '#' {
					rows[y].WriteString("█")
				} else {
					rows[y].WriteByte(' ')
				}
			}
		}
	}
	var b strings.Builder
	for y := range rows {
		b.WriteString(indent)
		b.WriteString(strings.TrimRight(rows[y].String(), " "))
		b.WriteByte('\n')
	}
	return b.String()
}
